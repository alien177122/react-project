export function getExerciseNote(exerciseKey: string, type: string): ExerciseNote {
  const base: ExerciseNote = TYPE_DEFAULTS[type] ?? TYPE_DEFAULTS.A!
  const override = EXERCISE_OVERRIDES[exerciseKey] ?? {}
  return { ...base, ...override }
}

export function getFormulaLabel(testReps: number): string {
  if (testReps < 5) return 'Brzycki modified: вес ÷ (1.0278 − 0.0278 × повт × 1.3)'
  if (testReps <= 8) return 'программная формула: вес ÷ (1.0278 − 0.0278 × повт × 1.2)'
  return 'модифицированная Эпли: вес × (1 + 0.0333 × повт × 1.1)'
}
